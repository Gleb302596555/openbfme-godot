#!/usr/bin/env python3
"""Ennorath audit (docs/ENNORATH_FACTION_PLAN.md, E1): writes the per-faction registry markdown from tools/mod/ennorath_graph.py's walk.

    ennorath_docs.py --base <ROTWK_INSTALL> --bfme2 <BFME2_INSTALL> --overlay <mod install> --faction FactionMen --docs docs/ennorath --dump <dir>

Only IDs, source file names, constant names and SHA-256 sums go into the markdown; no INI text, no values copied from game files beyond
the cost / time constant names the plan's registry fields need. The machine dump (graph.json, unresolved.json) goes to --dump, which
belongs under the ignored workspace/ennorath-audit/.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ennorath_graph as g  # noqa: E402


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def esc(x: str) -> str:
    return x.replace("|", "/")


def via_text(reached, node) -> str:
    v = reached.get(node)
    if not v:
        return "root"
    src, key = v[0]
    return esc(f"{src[0]}:{src[1]}.{key}")


def owners_of_sets(db, order):
    owners = defaultdict(list)  # command set -> [(object, key, condition)]
    for node in order:
        if node[0] == "object":
            for cs, key, cond in g.command_sets_of(db, node[1]):
                owners[cs].append((node[1], key, cond))
    return owners


def kind_short(db, name: str) -> str:
    k = g.kinds_of(db, name)
    for tag in ("HERO", "STRUCTURE", "HORDE", "CAVALRY", "INFANTRY", "MONSTER", "SIEGE_WEAPON", "VEHICLE", "DOZER", "PROJECTILE"):
        if tag in k:
            return tag
    return ",".join(sorted(k)[:2]) or "-"


def object_row(db, name: str):
    lm = g.leafmap(db, "object", name)
    d = db.defs.get(("object", name)) or {}
    return dict(cost=g.first(lm, "buildcost"), time=g.first(lm, "buildtime"), display=g.first(lm, "displayname"),
                kind=kind_short(db, name), src=d.get("src", "?"), parent=d.get("parent"))


def button_lines(db, cs: str, indent: str = ""):
    out = []
    for slot, b in g.set_buttons(db, cs):
        cmd, target, _ = g.button_info(db, b)
        out.append(f"{indent}- {slot}: `{b}` {cmd} {target}".rstrip())
    return out


def doc_heroes(db, reached, order, faction):
    pt = g.leafmap(db, "playertemplate", faction)
    heroes = g.first(pt, "buildableheroesmp").split()
    ring = g.first(pt, "buildableringheroesmp").split()
    L = [f"# {faction} - heroes (generated by tools/mod/ennorath_docs.py)", "",
         "IDs, command sets and ability buttons found by walking the mounted data. **INVENTORIED** only: nothing here says a hero or a button works.",
         "`CreateAHeroDummy` / `RingHeroDummy` are entry points; what they open is still to be traced.", ""]
    for h in heroes + ring:
        ob = db.defs.get(("object", h))
        L.append(f"## {h}")
        if not ob:
            L += ["- no object definition found (unresolved)", ""]
            continue
        r = object_row(db, h)
        L.append(f"- source: `{r['src']}`" + (f", parent `{r['parent']}`" if r["parent"] else ""))
        L.append(f"- BuildCost `{r['cost']}`, BuildTime `{r['time']}`, display `{r['display']}`")
        forms = []
        for k, v, _s, m in g.effective_fields(db, "object", h):
            if k.lower() in ("mountedtemplate", "respawnastemplate", "replacementobject", "initialpayload") and v.split():
                forms.append(f"{k}={v.split()[0]}" + (f" ({m})" if m else ""))
        if forms:
            L.append("- forms / replacements: " + ", ".join(sorted(set(forms))))
        for cs, key, cond in g.command_sets_of(db, h):
            L.append(f"- command set `{cs}` via `{key}` ({cond})")
            L += button_lines(db, cs, "  ")
        L.append("- status: data INVENTORIED; logic / UI / visuals TODO")
        L.append("")
    return "\n".join(L)


def doc_buildings(db, reached, order, faction, owners):
    structs = [n for (t, n) in order if t == "object" and "STRUCTURE" in g.kinds_of(db, n)]
    L = [f"# {faction} - buildings (generated by tools/mod/ennorath_docs.py)", "",
         "Structures reachable from the start and what their command sets build or buy. **INVENTORIED** only.", "",
         f"{len(structs)} structure objects reached. The count is an over-approximation: filter-style references are excluded, but prop objects of castle layouts are not.", "",
         "| Object | BuildCost | Command sets (condition) | First path |", "|---|---|---|---|"]
    for n in structs:
        r = object_row(db, n)
        sets = "; ".join(f"`{cs}` ({esc(c)})" for cs, _k, c in g.command_sets_of(db, n)) or "-"
        L.append(f"| `{n}` | `{r['cost'] or '-'}` | {sets} | {via_text(reached, ('object', n))} |")
    L.append("")
    for cs in [n for (t, n) in order if t == "commandset"]:
        own = owners.get(cs, [])
        if not any("STRUCTURE" in g.kinds_of(db, o) for o, _k, _c in own):
            continue
        L.append(f"### {cs}")
        L.append("owners: " + ", ".join(f"`{o}` ({esc(c)})" for o, _k, c in own))
        L += button_lines(db, cs)
        L.append("")
    return "\n".join(L)


def doc_units(db, reached, order, faction):
    prod = defaultdict(list)
    for cs in [n for (t, n) in order if t == "commandset"]:
        for slot, b in g.set_buttons(db, cs):
            _cmd, target, _ = g.button_info(db, b)
            if target.startswith("object="):
                prod[target.split("=", 1)[1]].append(f"{cs}:{b}")
    objs = [n for (t, n) in order if t == "object" and "STRUCTURE" not in g.kinds_of(db, n) and "HERO" not in g.kinds_of(db, n)]
    L = [f"# {faction} - units and summons (generated by tools/mod/ennorath_docs.py)", "",
         "Non-structure, non-hero objects reached. `Produced by` is a build button in a reached command set; the others come from OCLs, hordes, forms or weapons. "
         "**INVENTORIED** only.", "", f"{len(objs)} objects.", "",
         "| Object | Kind | BuildCost | Produced by | First path |", "|---|---|---|---|---|"]
    for n in objs:
        r = object_row(db, n)
        pb = "<br>".join(f"`{x}`" for x in prod.get(n, [])) or "-"
        L.append(f"| `{n}` | {r['kind']} | `{r['cost'] or '-'}` | {pb} | {via_text(reached, ('object', n))} |")
    return "\n".join(L)


def doc_upgrades(db, reached, order, faction, owners):
    rows = []
    for cs in [n for (t, n) in order if t == "commandset"]:
        for slot, b in g.set_buttons(db, cs):
            cmd, target, _ = g.button_info(db, b)
            if target.startswith("upgrade="):
                rows.append((target.split("=", 1)[1], b, cmd, f"{cs} ({slot})", ", ".join(f"`{o}`" for o, _k, _c in owners.get(cs, [])[:4])))
    L = [f"# {faction} - upgrades (generated by tools/mod/ennorath_docs.py)", "",
         "Buttons of reached command sets that buy an upgrade, and the objects that show them. **INVENTORIED** only.", "",
         f"{len(rows)} button rows.", "", "| Upgrade | Button | Command | Command set (slot) | Owners |", "|---|---|---|---|---|"]
    for r in sorted(rows):
        L.append(f"| `{r[0]}` | `{r[1]}` | {r[2]} | {esc(r[3])} | {r[4] or '-'} |")
    return "\n".join(L)


def doc_main(db, reached, order, unresolved, faction, notes):
    pt = g.leafmap(db, "playertemplate", faction)
    store, book, cast_set, rows = g.spells_table(db, reached, faction)
    c = defaultdict(int)
    for node in order:
        c[node[0]] += 1
    L = [f"# {faction} - generated graph and spell table, Ennorath 1.9.8 (tools/mod/ennorath_docs.py; hand-kept state is in {faction}.md)", "",
         "[Plan](../ENNORATH_FACTION_PLAN.md). Rows are **INVENTORIED** (found in the mounted data); logic, UI and visuals are **TODO** unless a row says otherwise. "
         "The graph walks reference fields of the mounted INI text; it is an over-approximation, not the engine's parse.", "",
         "## Profile (E0)", ""] + notes + ["", "## Graph size", "", "| Kind | Reached |", "|---|---:|"]
    for k in sorted(c):
        L.append(f"| {k} | {c[k]} |")
    L += ["", f"Unresolved tokens in reference-like fields: {len(unresolved)} (most are keywords such as `PRIMARY` / `OR` or engine-defined upgrades; the list is in the ignored dump).", "",
          "## Start (A)", ""]
    for key in ("side", "playableside", "startingbuilding", "startmoney", "intrinsicsciences", "intrinsicsciencesmp", "initialupgrades", "spellbookmp",
                "purchasesciencecommandsetmp", "buildableheroesmp", "buildableringheroesmp", "defaultplayeraitype"):
        if pt.get(key):
            L.append(f"- `{key}`: `{' / '.join(pt[key])}`")
    for k in sorted(k for k in pt if k.startswith("startingunit") and not k.startswith(("startingunitoffset", "startingunittactical"))):
        L.append(f"- `{k}`: `{pt[k][0]}`")
    L += ["", f"## Spell book: store `{store}` -> cast set `{cast_set}` (book object `{book}`)", "",
          "| Buy slot | Purchase button | Science | Cost | Prerequisites | Cast slot | Cast button | SpecialPowers needing this science | Module (type / tag) | Refs | Status |",
          "|---:|---|---|---:|---|---:|---|---|---|---|---|"]
    extra = []
    for r in rows:
        cast = "<br>".join(str(x[0]) for x in r["cast"]) or "-"
        castb = "<br>".join(f"`{x[1]}`" for x in r["cast"]) or "**none in the cast set**"
        pw = "<br>".join(f"`{x}`" for x in r["powers"]) or "-"
        mod = "<br>".join(f"`{m[1]}` / `{m[2]}`" for m in r["modules"]) or "-"
        refs = "<br>".join(esc(", ".join(m[3])) for m in r["modules"]) or "-"
        L.append(f"| {r['slot']} | `{r['button']}` | `{r['science']}` | {r['cost']} | {esc(r['prereq'])} | {cast} | {castb} | {pw} | {mod} | {refs} | INVENTORIED; behaviour TODO |")
        extra += [p for p in r["powers"] if p not in [x[2] for x in r["cast"]]]
    L += ["", "Powers that need one of these sciences but have no button in the cast set (AI, MM-map or hidden variants): "
          + (", ".join(f"`{p}`" for p in extra) or "none") + ". Each needs its own reachability answer.", ""]
    return "\n".join(L)


def write_expected(db, order, path: Path):
    """tab separated expectations for engine/tests/test_ennorath_men.cpp (OPENBFME_ENNORATH_EXPECTED): the data's own command sets, buttons and objects.
    Stays under the ignored workspace/: it is game data, never committed."""
    rows = []
    for typ, name in order:
        if typ == "commandset":
            for slot, b in g.set_buttons(db, name):
                rows.append(("set", name, str(slot), b))
        elif typ == "commandbutton":
            lm = g.leafmap(db, "commandbutton", name)
            first1 = lambda k: (lm.get(k) or [""])[0].split()[0] if (lm.get(k) or [""])[0].split() else ""
            rows.append(("button", name, first1("object"), first1("upgrade"), first1("specialpower"), ",".join((lm.get("science") or [""])[0].split())))
        elif typ in ("object", "objectreskin"):
            rows.append(("object", name))
    nl = chr(10)
    path.write_text(nl.join(chr(9).join(r) for r in rows) + nl, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    ap.add_argument("--bfme2", required=True)
    ap.add_argument("--overlay", required=True)
    ap.add_argument("--faction", required=True)
    ap.add_argument("--docs", required=True)
    ap.add_argument("--dump", required=True)
    ap.add_argument("--expected", default=None, help="write the tab separated expectations for the engine test here (under workspace/)")
    a = ap.parse_args()
    vfs = g.mount(Path(a.base), Path(a.overlay), Path(a.bfme2))
    db = g.load_db(vfs)
    reached, order, unresolved, _mods = g.walk(db, a.faction)
    dump = Path(a.dump)
    dump.mkdir(parents=True, exist_ok=True)
    (dump / "unresolved.json").write_text(json.dumps([{"node": f"{n[0]}:{n[1]}", "field": k, "token": t, "src": s} for n, k, t, s in unresolved], indent=1), encoding="utf-8")
    owners = owners_of_sets(db, order)
    overlay_archives = sorted({(e[3], e[0]) for e in vfs.files.values() if e[3].startswith("overlay")})
    notes = ["- mount order (lowest first): BFME2 1.06 `ini.big`, `_patch101.big`, `_patch103.big`, `bases.big` < RotWK 2.01 `INI.big`, `Bases.big`, `_patch201ini.big` < the Ennorath overlay's `.big` files",
             "- INI/INC text and castle layouts (`.bse`) only; this walk does not read models, textures, sounds or maps"]
    for lab, arc in overlay_archives:
        notes.append(f"- `{lab}` SHA-256 `{sha256_of(arc)}`")
    dd = Path(a.docs)
    dd.mkdir(parents=True, exist_ok=True)
    (dd / f"{a.faction}_Graph.md").write_text(doc_main(db, reached, order, unresolved, a.faction, notes), encoding="utf-8")
    (dd / f"{a.faction}_Heroes.md").write_text(doc_heroes(db, reached, order, a.faction), encoding="utf-8")
    (dd / f"{a.faction}_Buildings.md").write_text(doc_buildings(db, reached, order, a.faction, owners), encoding="utf-8")
    (dd / f"{a.faction}_Units.md").write_text(doc_units(db, reached, order, a.faction), encoding="utf-8")
    (dd / f"{a.faction}_Upgrades.md").write_text(doc_upgrades(db, reached, order, a.faction, owners), encoding="utf-8")
    if a.expected:
        write_expected(db, order, Path(a.expected))
    print("written", dd)


if __name__ == "__main__":
    main()
